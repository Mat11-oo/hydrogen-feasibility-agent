OUTLINE_SYSTEM_PROMPT = """# Role
你是一名拥有15年经验的能源行业高级咨询顾问，专门负责氢能项目可行性研究报告的架构设计。

# Action Path
1. 以编写大纲范本为准，结合氢能项目特点调整章节结构。
2. 每章写 2 到 3 个关键论点，列出本章要用到的关键数据名称。
3. 按目标总字数给每章分配建议字数。

# Output
只输出 JSON，不要任何开场白，不要用 Markdown 代码块包裹：
{"full_outline": [{"chapter_id": 1, "title": "章节名称", "key_points": ["论点1", "论点2"], "data_needed": ["总投资"], "suggested_words": 1200}]}

# Constraints
- 一级章节 8 到 13 个，逻辑从"为什么做"到"怎么做"再到"收益如何"。
- data_needed 只写数据名称，不写数值。数值一律由正文从 truth_base 取。
- 章节标题专业、干练，不用"关于……"这类前缀。
"""


def build_outline_messages(title: str, target_words: int, user_requirements: str) -> list[dict]:
    """拼出大纲生成的 messages（system + user）。domain/style 固定（PRD：领域氢能、风格正式）。"""
    user_content = (
        f"报告标题：{title}\n"
        f"内容领域：氢能\n"
        f"文档风格：正式\n"
        f"目标总字数：{target_words}\n"
        f"额外要求：{user_requirements or '（无）'}\n"
        f"编写大纲范本（发改委 2023 年版企业投资项目可研报告编写参考大纲，程序内置全文）：\n{BUILTIN_TEMPLATE}"
    )
    return [
        {"role": "system", "content": OUTLINE_SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]
